import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const service = await readFile('src/services/membership.js', 'utf8')
const page = await readFile('src/pages/AdminMembershipsPage.jsx', 'utf8')
const tierPage = await readFile('src/pages/AdminMembershipTiersPage.jsx', 'utf8')
const app = await readFile('src/App.jsx', 'utf8')
const layout = await readFile('src/layouts/AdminLayout.jsx', 'utf8')
const dashboard = await readFile('src/pages/AdminPage.jsx', 'utf8')

for (const callable of ['listMemberships', 'getUserMemberships', 'listMembershipTiers', 'createManualMembership', 'revokeMembership', 'createMembershipTier', 'updateMembershipTier', 'deactivateMembershipTier']) {
  assert.match(service, new RegExp(`callMembershipFunction\\('${callable}'`), `Missing Membership callable: ${callable}`)
}
assert.match(app, /path="memberships" element={<PermissionGate permission={PERMISSIONS\.MEMBERSHIP_READ}>/)
assert.match(app, /path="membership-tiers" element={<PermissionGate permission={PERMISSIONS\.MEMBERSHIP_UPDATE}>/)
assert.match(layout, /PERMISSIONS\.MEMBERSHIP_READ/)
assert.match(page, /PERMISSIONS\.MEMBERSHIP_ASSIGN/)
assert.match(page, /PERMISSIONS\.MEMBERSHIP_REVOKE/)
assert.match(page, /listMembershipTiers\(\)/)
assert.match(page, /const \[selectedTier, setSelectedTier\] = useState\(null\)/)
assert.match(page, /const searchTiers = useCallback/)
assert.match(page, /AsyncSearchSelect label="Membership Tier"/)
assert.match(service, /query = ''/)
assert.match(page, /membership-tier-summary/)
assert.match(page, /formTier\.description/)
assert.match(page, /Membership Tier/)
assert.match(page, /createManualMembership\(\{ userId: form\.userId, tierId: form\.tierId, startsAt, expiresAt \}\)/)
assert.match(page, /window\.confirm/)
assert.match(page, /getUserMemberships\(/)
assert.match(tierPage, /includeInactive: true/)
assert.match(tierPage, /PERMISSIONS\.MEMBERSHIP_UPDATE/)
assert.match(tierPage, /deactivateMembershipTier\(/)
assert.match(tierPage, /generateMembershipTierId/)
assert.match(tierPage, /Mã kỹ thuật/)
assert.match(tierPage, /createMembershipTier\(\{ tierId/)
assert.doesNotMatch(tierPage, /<label[^>]*>Tier ID<input/)
assert.doesNotMatch(service, /actorUid|systemRole|permissions|updateDoc|setDoc|deleteDoc/)
assert.doesNotMatch(page, /VIP1|VIP2|VIP3/)
assert.doesNotMatch(tierPage, /VIP1|VIP2|VIP3/)
assert.match(dashboard, /PERMISSIONS\.MEMBERSHIP_READ/)

console.log('Frontend Membership test PASS: permission routes, dynamic tier IDs, callable-only mutations, bounded reads and UX explanations verified.')
